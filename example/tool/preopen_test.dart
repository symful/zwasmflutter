/// `_start` calls `fd_prestat_get(3, 0)` and exits with its errno:
/// 0 when fd 3 is a preopen, 8 (EBADF) when it is not.
final prestatWasm = Uint8List.fromList(const [
  0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00, 0x01, 0x0e, 0x03, 0x60,

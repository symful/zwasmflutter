int runStart({required bool preopen}) {
  final engine = Zwasm.createEngine();
  final module = engine.compile(prestatWasm);
  final wasi = ZwasmWasiConfig();
  try {
    if (preopen) wasi.preopenDir('.', '/sandbox');
    final instance = module.instantiate(
      engine: ZwasmEngineChoice.interp,
      wasi: wasi,
    );
    try {
      try {
        instance.findFunction('_start')!.call([]);
        return -1;
      } on ZwasmException catch (e) {
        if (!e.isWasiExit) rethrow;
        return instance.wasiExitCode ?? -1;
      }
    } finally {
      instance.dispose();
    }
  } finally {
    wasi.dispose();
    module.dispose();
    engine.dispose();
  }
}

Future<void> main() async {
  await Zwasm.initialize();
  if (Platform.isWindows) {
    final wasi = ZwasmWasiConfig();
    try {
      wasi.preopenDir('.', '/sandbox');
      throw StateError('preopens should be disabled on Windows');
    } on UnsupportedError catch (e) {
      print('Windows preopens disabled as expected: $e');
    } finally {
      wasi.dispose();
    }
    print('OK');
    return;
  }
  final withPreopen = runStart(preopen: true);
  final withoutPreopen = runStart(preopen: false);
  print('preopen exit=$withPreopen no-preopen exit=$withoutPreopen');
  if (withPreopen != 0 || withoutPreopen != 8) {
    throw StateError('preopen behavior is wrong');
  }
  print('OK');
}
